/**
 * 手势的共用数值。
 *
 * 放在一处是因为**同一件事在两个地方各写了一个数**：日历的跨天拖拽
 * （`hooks/use-cross-day-drag`）和收集箱的排序（`components/reorderable-list`）
 * 都是"长按拾起再拖"，原先却分别是 200ms 与 220ms ——
 * 两个数字差 20ms 没人看得出来，但用户在同一只手上做出来的动作是一样的，
 * 一处调了另一处没调，手感就会莫名其妙地不一致。
 */

/**
 * 长按多久才算"拿起"（毫秒）。
 *
 * 它同时是**防误触的闸门**：低于这个值就还是一次普通的点按（打开详情），
 * 所以调小会让"想点开却拖起来了"，调大则让"想拖却半天拿不起来"。
 * 取 300ms —— 比系统默认的长按（500ms）短，长按不至于要"数着秒等"；
 * 又比原先的 200ms 长，手指按下瞬间的抖动不容易被判成要拖拽。
 */
export const LONG_PRESS_PICKUP_MS = 300;
